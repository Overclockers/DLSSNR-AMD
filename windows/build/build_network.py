#!/usr/bin/env python3
"""Build the Windows network (AMD proprietary driver, LLPC) from windows/shaders/<arch>/pipelines.json.

    build_network.py <arch> [--out DIR] [--check DIR]

Writes (default build/windows/<arch>/network):
    g_<name>.spv + the four marker files   the network, what --spv-dir points at
    runtime/                                 the passes around it (windows/shaders/passes)
    temporal/                                the temporal variants and the motion estimator

LLPC leaves the large per-fragment loops of fswin_t.comp rolled and spills the arrays they
index to scratch, so every fswin_t pipeline is preprocessed, its pair quantisation loops made
four-wide (windows/build/quad_quant_glsl.py; --no-quad keeps them; it also drops the f32 -> f16 -> f32
round trips RADV deletes anyway, NR_Q32_DIRECT=0 in the environment keeps them), fully unrolled
(windows/build/unroll_glsl.py) and compiled from the result.

The host must be compiled with the same constants: windows/build/arch/<arch>.sh.
--check DIR compares every network SPV and marker with DIR byte for byte and
lists the differences (exit 1 if any).
"""
import argparse
from contextlib import nullcontext
import hashlib
import importlib.util
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

try:
    from experiment_support import ShaderCache, StageTimings, digest
except ModuleNotFoundError:
    # Existing discovery scripts load this builder directly from source snapshots.
    spec = importlib.util.spec_from_file_location('nr_experiment_support', Path(__file__).with_name('experiment_support.py'))
    support = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(support)
    ShaderCache, StageTimings, digest = support.ShaderCache, support.StageTimings, support.digest

R = Path(__file__).resolve().parents[2]
GLSLANG = R / 'toolchain/glslang/bin/glslang'
RUNTIME = ['runtime_alpha', 'runtime_encode', 'runtime_encode_sampled', 'runtime_encode_direct', 'runtime_transfer', 'runtime_transfer_packed', 'runtime_prep', 'runtime_depth', 'cascade_lograt', 'cascade_blur', 'cascade_feed']
MOTION = ['motion_luma', 'motion_estimate']
# Runtime alternates consume the base graph node's packed weights and push record.
RUNTIME_NETWORK = {'runtime_preencode': ('fswinimagepreds32', ['NR_FUSED_ENCODE=1'])}


QUAD = True   # --no-quad: the pair loops as written (A/B)
CACHE = None
TIMINGS = None
TOOL_IDENTITY = None


def stage(name, **details):
    return TIMINGS.stage(name, **details) if TIMINGS else nullcontext()


def preprocess(arch, src, defines):
    with stage('preprocess', source=str(src)):
        r = subprocess.run([str(GLSLANG), '-E', '-I' + str(R / 'windows/shaders' / arch / 'include')]
                           + ['-D' + d for d in defines] + [str(src)], capture_output=True, text=True)
        if r.returncode:
            sys.exit(f'glslang -E failed on {src}:\n{r.stdout}{r.stderr}')
        return r.stdout


def glslang(arch, src, defines, out, unroll=False, network=False):
    original = src
    original_defines = list(defines)
    transformed = unroll or (network and QUAD)
    preprocessed = preprocess(arch, src, defines) if transformed or CACHE else None
    key = None
    if CACHE:
        # Compiler preprocessing resolves actual conditional/transitive includes.
        # Paths stay in the key because source names can affect generated bytes.
        identity = dict(tool=TOOL_IDENTITY, source=str(src.resolve()), arch=arch,
                        defines=defines, unroll=unroll, network=network, quad=QUAD,
                        q32_direct=os.environ.get('NR_Q32_DIRECT', '1'),
                        target='vulkan1.3', preprocessed=preprocessed)
        key = hashlib.sha256(json.dumps(identity, sort_keys=True).encode('utf-8')).hexdigest()
        with stage('cache', output=str(out)):
            if CACHE.restore(key, out):
                return
    if unroll or (network and QUAD):
        pre = out.with_suffix('.pre.comp')
        with stage('transform', source=str(src)):
            pre.write_text(preprocessed)
            if QUAD:
                subprocess.run([sys.executable, str(R / 'windows/build/quad_quant_glsl.py'), str(pre), str(pre)],
                               check=True, stdout=subprocess.DEVNULL)
            if unroll:
                subprocess.run([sys.executable, str(R / 'windows/build/unroll_glsl.py'), str(pre), str(pre)],
                               check=True, stdout=subprocess.DEVNULL)
        src, defines = pre, []
    cmd = [str(GLSLANG), '-V', '--target-env', 'vulkan1.3',
           '-I' + str(R / 'windows/shaders' / arch / 'include')]
    cmd += ['-D' + d for d in defines] + [str(src), '-o', str(out)]
    with stage('compile', source=str(original), output=str(out)):
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode:
            sys.exit(f'glslang failed on {src}:\n{r.stdout}{r.stderr}')
    if unroll or (network and QUAD):
        src.unlink()
    if CACHE:
        if preprocess(arch, original, original_defines) != preprocessed:
            out.unlink(missing_ok=True)
            raise RuntimeError('shader inputs changed during compilation; discard this build')
        CACHE.store(key, out)


def main():
    global QUAD, GLSLANG, CACHE, TIMINGS, TOOL_IDENTITY
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('arch')
    ap.add_argument('--out', type=Path)
    ap.add_argument('--glslang', type=Path, default=GLSLANG)
    ap.add_argument('--define', action='append', default=[],
                    help='extra define for every network pipeline (diagnostics, e.g. NR_PROF_OFF=...)')
    ap.add_argument('--check', type=Path)
    ap.add_argument('--no-quad', action='store_true',
                    help='keep the pair quantisation loops (windows/build/quad_quant_glsl.py off)')
    ap.add_argument('--incremental', action='store_true', help='reuse hash-verified compiled shader entries')
    ap.add_argument('--cache-dir', type=Path, help='private shader cache (requires --incremental)')
    ap.add_argument('--timings', type=Path, help='wall-clock JSONL (default: sibling of output directory)')
    a = ap.parse_args()
    QUAD = not a.no_quad
    GLSLANG = a.glslang
    if a.cache_dir and not a.incremental:
        ap.error('--cache-dir requires --incremental')
    table = json.loads((R / 'windows/shaders' / a.arch / 'pipelines.json').read_text())
    out = a.out or R / 'build/windows' / a.arch / 'network'
    out = out.resolve()
    if out == Path(out.anchor) or out == R or out in R.parents or out.is_relative_to(R / 'windows'):
        ap.error('--out must not overwrite the repository or Windows sources')
    TIMINGS = StageTimings(a.timings or out.parent / (out.name + '.timings.jsonl'))
    if a.incremental:
        CACHE = ShaderCache(a.cache_dir or R / 'build/windows/shader-cache')
        if CACHE.directory.resolve().is_relative_to(out):
            ap.error('--cache-dir must be outside --out')
        TOOL_IDENTITY = {'compiler': digest(GLSLANG), 'python': sys.version,
                         'scripts': {name: digest(R / 'windows/build' / name) for name in
                                     ('build_network.py', 'quad_quant_glsl.py', 'unroll_glsl.py',
                                      'experiment_support.py')}}
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)

    pipelines = table['pipelines']
    for name, e in pipelines.items():
        glslang(a.arch, R / 'windows/shaders' / a.arch / e['source'], e['defines'] + a.define, out / f'g_{name}.spv',
                unroll=e['source'] == 'fswin_t.comp', network=True)
    for name, text in table['markers'].items():
        (out / name).write_text('\n'.join(text) + '\n' if isinstance(text, list) else text + '\n')
    (out / 'runtime').mkdir()
    (out / 'temporal').mkdir()
    for name, v in table['variants'].items():
        base = pipelines[v['base']]
        glslang(a.arch, R / 'windows/shaders' / a.arch / base['source'], base['defines'] + v['add'],
                out / 'temporal' / f'{name}.spv', unroll=base['source'] == 'fswin_t.comp', network=True)
    for k in MOTION:
        glslang(a.arch, R / 'windows/shaders/passes' / f'{k}.comp', [], out / 'temporal' / f'{k}.spv')
    shutil.copy2(out / 'shader-constants.txt', out / 'temporal' / 'shader-constants.txt')
    for k in RUNTIME:
        sampled_encode = k in ('runtime_encode_sampled', 'runtime_encode_direct')
        source = 'runtime_encode' if sampled_encode else k
        defines = ['NR_ENCODE_SAMPLED=1'] if sampled_encode else []
        if k == 'runtime_encode_direct':
            defines.append('NR_ENCODE_DIRECT=1')
        if k == 'runtime_transfer_packed':
            source = 'runtime_transfer'
            defines.append('NR_TRANSFER_PACKED=1')
        glslang(a.arch, R / 'windows/shaders/passes' / f'{source}.comp', defines, out / 'runtime' / f'{k}.spv')
    for name, (base_name, extra) in RUNTIME_NETWORK.items():
        base = pipelines[base_name]
        glslang(a.arch, R / 'windows/shaders' / a.arch / base['source'], base['defines'] + a.define + extra,
                out / 'runtime' / f'{name}.spv', unroll=base['source'] == 'fswin_t.comp', network=True)
    print(f'{out}: {len(pipelines)} network pipelines, {len(table["variants"]) + len(MOTION)} temporal, '
          f'{len(RUNTIME) + len(RUNTIME_NETWORK)} runtime')
    print('wall-clock seconds:', json.dumps(TIMINGS.totals, sort_keys=True))
    if CACHE:
        print(f'shader cache: {CACHE.hits} hits, {CACHE.misses} misses')

    if a.check:
        expected = {p.relative_to(out) for p in out.rglob('*') if p.is_file()}
        saved = {p.relative_to(a.check) for p in a.check.rglob('*') if p.is_file()}
        bad = [str(p) for p in sorted(expected | saved)
               if p not in expected or p not in saved or (a.check / p).read_bytes() != (out / p).read_bytes()]
        print('check against', a.check, ':', 'identical' if not bad else 'DIFFERENT: ' + ' '.join(bad))
        sys.exit(1 if bad else 0)


if __name__ == '__main__':
    main()
